            Paragraph("<b>Medium</b>", ParagraphStyle("C4", parent=body_style, fontName="Helvetica-Bold", textColor=c_yellow, alignment=1)),
            Paragraph("<b>Low</b>", ParagraphStyle("C5", parent=body_style, fontName="Helvetica-Bold", textColor=c_blue, alignment=1)),
            Paragraph("<b>Secrets</b>", ParagraphStyle("C6", parent=body_style, fontName="Helvetica-Bold", alignment=1)),
            Paragraph("<b>Score</b>", ParagraphStyle("C7", parent=body_style, fontName="Helvetica-Bold", textColor=status_color, alignment=1)),
