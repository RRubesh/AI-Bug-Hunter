def safe_escape(val) -> str:
    if val is None:
        return ""
    return html.escape(str(val))

def mask_secret(secret_str: str) -> str:
    if not secret_str:
        return "********"
    s = secret_str.strip()
    if len(s) <= 8:
        return s[:2] + "****" + s[-2:]
    return s[:3] + "***************" + s[-4:]

class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Header (Pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "AI BUG HUNTER  |  ENTERPRISE SECURITY ASSESSMENT REPORT")
            self.setStrokeColor(colors.HexColor("#06b6d4"))
            self.setLineWidth(1)
            self.line(54, 742, 558, 742)
            
        # Footer (All Pages)
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, page_str)
        self.drawString(54, 36, "Generated by AI Bug Hunter  •  AI-Powered Defensive Security & Vulnerability Analysis")
        self.setStrokeColor(colors.HexColor("#1e293b"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)
        
        self.restoreState()


def generate_pdf_report(scan: Scan, project: Project, vulnerabilities: list, output_path: Path):
    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=72,
        bottomMargin=72
    )

    styles = getSampleStyleSheet()
    
    # Palette
    c_navy_bg = colors.HexColor("#050816")
    c_cyan = colors.HexColor("#06b6d4")
    c_violet = colors.HexColor("#8b5cf6")
    c_red = colors.HexColor("#ef4444")
    c_orange = colors.HexColor("#f97316")
    c_yellow = colors.HexColor("#eab308")
    c_blue = colors.HexColor("#3b82f6")
    c_green = colors.HexColor("#10b981")
    c_dark_card = colors.HexColor("#0f172a")
    c_border = colors.HexColor("#1e293b")
    c_text_muted = colors.HexColor("#64748b")
    c_text_dark = colors.HexColor("#0f172a")
    c_text_body = colors.HexColor("#334155")

    # Typography Styles
    title_style = ParagraphStyle(
        "CoverTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=26,
        leading=32,
        textColor=c_text_dark,
        alignment=0,
        spaceAfter=6
    )
    
